// The Overview's Demo: a simulated organisation, so anyone can see what RoleMatch looks like after months of use beside their own Live figures (owner,
// 10 Nov 2026: "everything about the demo dashboard must operate how the real one would"). Its activity is generated minute by minute over six months of
// working hours (quieter at weekends), from a fixed seed, so the same moment always shows the same company. Every figure is then worked out from that
// history for the chosen period, the same way the server works out Live from real records (server/src/orgOverview.ts). Because it is generated by the
// clock, new activity appears as minutes pass. Nothing is stored or sent: it is built in this browser and labelled Demo wherever it shows.
import type { OverviewData } from "./types";

/** A small seeded random-number generator: the same seed gives the same company every time. */
function seeded(seed: number) { return () => { seed |= 0; seed = (seed + 0x6d2b79f5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const MINUTE = 60_000, DAY = 86_400_000;
const FIRST = ["Lerato", "Sipho", "Ayesha", "Thandi", "Johan", "Nomsa", "Kevin", "Zanele", "Pieter", "Aisha", "Michael", "Busisiwe", "Rohan", "Grace", "Kabelo", "Meera", "Farai", "Elena", "Nandi", "Adrian", "Thabo", "Lindiwe", "Ruan", "Naledi", "Ahmed", "Chloe", "Sibusiso", "Priya"];
const LAST = ["Khumalo", "Ndlovu", "Patel", "Mokoena", "Pretorius", "Dlamini", "Naidoo", "Khumalo", "van der Merwe", "Govender", "Chen", "Dube", "Okonkwo", "Sebola", "Pillay", "Moyo", "Petersen", "Zulu", "Botha", "Modise", "Mahlangu", "Fourie", "Mthembu", "Smith", "Jacobs"];
const TEAM = ["Thandi M.", "Sipho N.", "Lerato K.", "Johan P."];
const CITIES = ["Johannesburg", "Sandton", "Cape Town", "Durban", "Pretoria", "Rosebank", "Centurion"];
// Jobs the simulated company recruits for, each in the standard department the job reader would place it in (server/src/jobReader.ts, JOB_DEPARTMENTS).
const JOBS: [string, string][] = [["Head of Technology", "Technology"], ["Software Engineer", "Technology"], ["Cloud Engineer", "Technology"], ["IT Service Manager", "Technology"],
  ["Data Analyst", "Data and analytics"], ["Data Scientist", "Data and analytics"], ["Chief Financial Officer", "Finance"], ["Financial Accountant", "Finance"], ["Management Accountant", "Finance"],
  ["Risk Analyst", "Risk and compliance"], ["Compliance Officer", "Risk and compliance"], ["HR Business Partner", "Human resources"], ["Operations Manager", "Operations"],
  ["Claims Assessor", "Operations"], ["Sales Account Manager", "Sales and marketing"], ["Marketing Manager", "Sales and marketing"], ["Customer Service Team Leader", "Customer service"],
  ["Programme Manager", "Project and programme management"], ["Legal Counsel", "Legal"], ["Executive Assistant", "Administration"]];

interface Person { id: string; name: string; role: string; group: string; years: number; at: number }
interface Job { id: string; title: string; group: string; location: string; opened: number; closed: number | null; noTitle?: boolean }
interface Move { candidate: string; job: string; status: "shortlisted" | "interviewing" | "hired"; at: number }
interface Match { candidate: string; job: string; score: number; at: number }
interface Event { who: string; what: string; at: number }

/** The simulated company as it starts: six months back from the start of `now`'s day, with its first jobs open. */
function begin(now: number) {
  const rnd = seeded(20261110), start = Math.floor((now - 180 * DAY) / DAY) * DAY;
  const people: Person[] = [], jobs: Job[] = [], moves: Move[] = [], matches: Match[] = [], events: Event[] = [], failed: number[] = [];
  const h = { start, rnd, people, jobs, moves, matches, events, failed, stageOf: new Map<string, Move["status"]>() /* candidate|job -> furthest stage */,
    open: [] as Job[] /* the jobs not closed, in the order they were opened */, next: start /* the first minute not yet lived */, steps: 0 /* minutes lived */ };
  for (let i = 0; i < 26; i++) openJob(h, start - Math.floor(rnd() * 40) * DAY);   // open when the history starts
  h.open.push(...jobs);
  return h;
}
type History = ReturnType<typeof begin>;
function openJob(h: History, at: number) { const [title, group] = JOBS[Math.floor(h.rnd() * JOBS.length)]; const j: Job = { id: `j${h.jobs.length}`, title, group, location: CITIES[Math.floor(h.rnd() * CITIES.length)], opened: at, closed: null, noTitle: h.rnd() < 0.03 }; h.jobs.push(j); return j; }

/**
 * Lives the company's history on from where it stopped up to `now`, minute by minute through working hours. The same seed and the same minutes give the
 * same company as building it from the start. It used to be rebuilt from the start every minute (about 108,000 working minutes, each filtering every job:
 * some 20 million steps on the main thread, 50 to 85 ms on a fast Mac, far more on a phone, once a minute while the Demo is shown; code review, 16 Nov 2026,
 * G-M12). Now each minute adds only the minutes since the last look, and the open jobs are kept as a list instead of being found again every minute.
 */
function liveOn(h: History, now: number) {
  const { rnd, people, jobs, moves, matches, events, failed, stageOf, open } = h;
  const name = () => `${FIRST[Math.floor(rnd() * FIRST.length)]} ${LAST[Math.floor(rnd() * LAST.length)]}`;
  let t = h.next;
  for (; t <= now; t += MINUTE) {
    const d = new Date(t), hour = d.getHours(), weekend = d.getDay() === 0 || d.getDay() === 6;
    if (hour < 8 || hour >= 18) { t += (hour < 8 ? 8 - hour : 24 - hour + 8) * 60 * MINUTE - MINUTE; continue; }   // jump to the next working morning
    h.steps++;
    const pace = weekend ? 0.15 : 1, who = TEAM[Math.floor(rnd() * TEAM.length)];
    // `open` is the jobs open as this minute began: a job opened or closed in it joins or leaves the list at the minute's end, as before.
    let opened: Job | null = null, closed: Job | null = null;
    if (rnd() < 0.0016 * pace) { const j = openJob(h, t); opened = j; events.push({ who, what: `Added a job: ${j.title}`, at: t }); }
    if (open.length > 18 && rnd() < 0.0012 * pace) { const j = open[Math.floor(rnd() * open.length)]; j.closed = t; closed = j; events.push({ who, what: `Closed a job: ${j.title}`, at: t }); }
    if (rnd() < 0.085 * pace) {
      const [role, group] = JOBS[Math.floor(rnd() * JOBS.length)], years = Math.max(0, Math.round(rnd() ** 1.4 * 24));
      const p: Person = { id: `c${people.length}`, name: name(), role, group, years, at: t }; people.push(p);
      if (rnd() < 0.18) events.push({ who, what: `Uploaded a CV: ${p.name}`, at: t });
    }
    if (rnd() < 0.0025 * pace) failed.push(t);
    if (people.length && open.length && rnd() < 0.07 * pace) {
      const c = people[people.length - 1 - Math.floor(rnd() * Math.min(people.length, 400))], j = open[Math.floor(rnd() * open.length)];
      const score = Math.round(52 + rnd() ** 0.7 * 44); matches.push({ candidate: c.id, job: j.id, score, at: t });
      if (rnd() < 0.08) events.push({ who, what: `Matched ${c.name} against ${j.title}`, at: t });
      if (score >= 80 && rnd() < 0.22 && !stageOf.has(`${c.id}|${j.id}`)) { stageOf.set(`${c.id}|${j.id}`, "shortlisted"); moves.push({ candidate: c.id, job: j.id, status: "shortlisted", at: t }); events.push({ who, what: `Moved ${c.name} to shortlisted for ${j.title}`, at: t }); }
    }
    if (moves.length && rnd() < 0.03 * pace) {
      const m = moves[moves.length - 1 - Math.floor(rnd() * Math.min(moves.length, 60))], key = `${m.candidate}|${m.job}`, now2 = stageOf.get(key);
      const next = now2 === "shortlisted" ? (rnd() < 0.7 ? "interviewing" : null) : now2 === "interviewing" && rnd() < 0.3 ? "hired" : null;
      // ids are positions ("c12" is people[12]), so a person and a job are found at once rather than searched for
      if (next) { stageOf.set(key, next); moves.push({ candidate: m.candidate, job: m.job, status: next, at: t }); const c = people[Number(m.candidate.slice(1))], j = jobs[Number(m.job.slice(1))]; events.push({ who, what: `Moved ${c.name} to ${next} for ${j.title}`, at: t }); }
    }
    if (closed) open.splice(open.indexOf(closed), 1);
    if (opened) open.push(opened);
  }
  h.next = t;
  return h;
}
/** The whole history up to `now`, built from the start (what the kept history must always equal). */
export const historyFromStart = (now: number) => liveOn(begin(now), now);

let cached: { minute: number; h: History } | null = null;
/** The kept history, lived on to `minute`. Built from the start only on the first look, when the six months move on to a new day, or if asked for an
 *  earlier minute than it has reached. */
export function demoHistory(minute: number): History {
  const now = minute * MINUTE, start = Math.floor((now - 180 * DAY) / DAY) * DAY;
  if (!cached || cached.h.start !== start || cached.minute > minute) cached = { minute, h: begin(now) };
  cached.minute = minute;
  return liveOn(cached.h, now);
}

/** The Demo company's figures for the last `days` days, as of now: built exactly as Live's are, from its own history. */
export function demoOverview(days: number, nowMs = Date.now()): OverviewData {
  const minute = Math.floor(nowMs / MINUTE), key = `${minute}|${days}`;
  // The same minute's figures are worked out once: the Overview asks every 15 seconds, and the figures only change by the minute.
  if (figures.minute !== minute) { figures.minute = minute; figures.byKey.clear(); }
  const kept = figures.byKey.get(key);
  if (kept) return kept;
  const made = figuresFor(days, minute);
  figures.byKey.set(key, made);
  return made;
}
const figures = { minute: -1, byKey: new Map<string, OverviewData>() };
function figuresFor(days: number, minute: number): OverviewData {
  // The period is the days the chart draws, Johannesburg's (UTC+2, no summer time), as Live's are (server/src/orgOverview.ts): today and the days before
  // it, from the first one's midnight; the period before is as long as this one so far. Code review, 16 Nov 2026, G-M1: "now minus N days" counted hours
  // of the oldest day that no day drew.
  const h = demoHistory(minute), now = minute * MINUTE, SAST = 2 * 3_600_000;
  const dayKey = (t: number) => new Date(t + SAST).toISOString().slice(0, 10), today = Date.parse(`${dayKey(now)}T00:00:00Z`) - SAST, from = today - (days - 1) * DAY;
  const inP = (t: number) => t >= from && t <= now, inPrev = (t: number) => t >= from - days * DAY && t < now - days * DAY;
  const dates = Array.from({ length: days }, (_, i) => dayKey(today + (i - (days - 1)) * DAY)), at = new Map(dates.map((d, i) => [d, i]));
  const per = (ts: number[]) => { const out = dates.map(() => 0); for (const t of ts) { const i = at.get(dayKey(t)); if (i !== undefined && inP(t)) out[i]++; } return out; };
  const open = h.jobs.filter((j) => j.opened <= now && (j.closed === null || j.closed > now));
  const latest = new Map<string, string>(); for (const m of h.moves) latest.set(`${m.candidate}|${m.job}`, m.status);
  // On shortlists now: for jobs still open; the period's flow: moves to each stage in the period (as the server works them out).
  const openIds = new Set(open.map((j) => j.id)), forward = [...latest.entries()].filter(([k]) => openIds.has(k.split("|")[1]));
  const moved = (st: Move["status"]) => h.moves.filter((m) => m.status === st && inP(m.at)).length;
  const shortlistedNow = forward.length, shortlistEvents = h.moves.filter((m) => m.status === "shortlisted");
  const lastMove = new Map<string, number>(); for (const m of h.moves) lastMove.set(`${m.candidate}|${m.job}`, m.at);
  const peopleIn = h.people.filter((p) => inP(p.at)), matchedIn = new Set(h.matches.filter((m) => inP(m.at)).map((m) => m.candidate));
  const byId = new Map(h.people.map((p) => [p.id, p])), jobById = new Map(h.jobs.map((j) => [j.id, j]));
  const periodMatches = h.matches.filter((m) => inP(m.at)), best = new Map<string, Match>();
  for (const m of periodMatches) { const k = `${m.candidate}|${m.job}`, cur = best.get(k); if (!cur || m.at > cur.at) best.set(k, m); }
  const strongest = [...best.values()].sort((a, b) => b.score - a.score).slice(0, 3).map((m) => { const c = byId.get(m.candidate)!, j = jobById.get(m.job)!; return { candidateId: c.id, candidateName: c.name, candidateRole: c.role, jobId: j.id, jobTitle: j.title, jobLocation: j.location, score: m.score }; });
  // Each department's open jobs and the candidates whose work belongs to it, as the server counts them.
  const fam = new Map<string, { open: number; candidates: number }>(), famOf = (g: string) => fam.get(g) ?? (fam.set(g, { open: 0, candidates: 0 }), fam.get(g)!);
  for (const j of open) famOf(j.group).open++;
  for (const p of h.people) if (p.at <= now) famOf(p.group).candidates++;
  const bands = [["Up to 2 years", 0, 3], ["3 to 5 years", 3, 6], ["6 to 10 years", 6, 11], ["Over 10 years", 11, 99]] as const;
  const month = dayKey(now).slice(0, 7), monthStart = Date.parse(`${month}-01T00:00:00Z`) - SAST;   // Johannesburg's month, as Live's (C-M5)
  const usedRand = Math.round(h.people.filter((p) => p.at >= monthStart && p.at <= now).length * 0.04 + h.matches.filter((m) => m.at >= monthStart && m.at <= now).length * 1.35);
  const ago = (t: number) => new Date(t).toISOString();
  return {
    days, generatedAt: new Date(now).toISOString(),
    credits: { usedUsd: +(usedRand / 18.5).toFixed(2), usedRand, month, allowanceRand: 6000 },
    candidates: { total: h.people.filter((p) => p.at <= now).length, inPeriod: peopleIn.length, previous: h.people.filter((p) => inPrev(p.at)).length },
    jobs: { open: open.length, newInPeriod: h.jobs.filter((j) => inP(j.opened)).length },
    shortlisted: { count: shortlistedNow, jobs: new Set(forward.map(([k]) => k.split("|")[1])).size, previous: shortlistEvents.filter((m) => inPrev(m.at)).length },
    series: { dates, cv: per(h.people.map((p) => p.at)), jobs: per(h.jobs.map((j) => j.opened)), match: per(h.matches.map((m) => m.at)), sl: per(shortlistEvents.map((m) => m.at)) },
    pipeline: { read: peopleIn.length, matched: matchedIn.size, shortlisted: moved("shortlisted"), interviewing: moved("interviewing"), hired: moved("hired") },
    strongest,
    families: [...fam.entries()].map(([name, f]) => ({ name, ...f })).sort((a, b) => b.open - a.open || b.candidates - a.candidates || a.name.localeCompare(b.name)),
    experience: bands.map(([band, lo, hi]) => ({ band, count: peopleIn.filter((p) => p.years >= lo && p.years < hi).length })),
    attention: demoAttention(h, now, open, forward, lastMove),
    activity: h.events.filter((e) => e.at <= now).slice(-50).reverse().map((e) => ({ who: e.who, what: e.what, at: ago(e.at) })),
  };
}

// Needs attention, by the same rules and in the same order as the server (server/src/attention.ts): work that waits on a recruiter, only when there is some.
function demoAttention(h: History, now: number, open: Job[], forward: [string, string][], lastMove: Map<string, number>): OverviewData["attention"] {
  const openIds = new Set(open.map((j) => j.id)), openGroups = new Set(open.map((j) => j.group));
  const idle = (k: string, days: number) => (lastMove.get(k) ?? now) < now - days * DAY;
  const best = new Map<string, Match>(); for (const m of h.matches) if (m.at > now - 30 * DAY && m.at <= now) { const k = `${m.candidate}|${m.job}`, cur = best.get(k); if (!cur || m.at > cur.at) best.set(k, m); }
  const staged = new Set(forward.map(([k]) => k)), matchedPeople = new Set(h.matches.filter((m) => m.at <= now).map((m) => m.candidate));
  const counts: [string, string, string, number][] = [
    ["interview-no-update", "Interview stage, no update", "In an interview stage for 5+ days without a change", forward.filter(([k, s]) => s === "interviewing" && idle(k, 5)).length],
    ["shortlist-waiting", "Shortlisted, waiting", "On a shortlist for 5+ days without a next step", forward.filter(([k, s]) => s === "shortlisted" && idle(k, 5)).length],
    ["strong-not-acted", "Strong matches not acted on", "Scored 80+ by the AI, not yet on the job's list or turned down", [...best.entries()].filter(([k, m]) => m.score >= 80 && openIds.has(m.job) && !staged.has(k) && !h.stageOf.has(k)).length],
    ["job-no-shortlist", "Open jobs with no shortlist", "Open 7+ days with nobody shortlisted", open.filter((j) => j.opened < now - 7 * DAY && !forward.some(([k]) => k.endsWith(`|${j.id}`))).length],
    ["new-not-matched", "New candidates not matched", "Added 2+ days ago, an open job in their department, not matched yet", h.people.filter((p) => p.at < now - 2 * DAY && p.at > now - 14 * DAY && !matchedPeople.has(p.id) && openGroups.has(p.group)).length],
  ];
  return counts.filter(([, , , n]) => n > 0).map(([id, title, detail, count]) => ({ id, title, detail, count }));
}
