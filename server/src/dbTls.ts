const SAME_MACHINE = /^(?:localhost|127(?:\.\d{1,3}){3}|\[?::1\]?|host\.docker\.internal|host\.containers\.internal|[a-z][a-z0-9-]*)$/i;   // the last is a container name, which has no dots

/** The encryption options for a database address. Every database client outside the tests uses these. */
export function dbTls(url: string): { ssl: false | { ca: string[]; rejectUnauthorized: true; minVersion: "TLSv1.2" } } {
  if (SAME_MACHINE.test(new URL(url).hostname)) return { ssl: false };
  return { ssl: { ca: [SUPABASE_ROOT_2021], rejectUnauthorized: true, minVersion: "TLSv1.2" } };
}
